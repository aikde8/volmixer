def kuit_marker(entry):
    ctx = entry.get("ctx") or ""
    return ctx.split()[0] if ctx.startswith("@") else ""


def msgctxt(entry):
    """gettext msgctxt for an entry: '[@kuit-marker ]key'."""
    marker = kuit_marker(entry)
    return marker + " " + entry["key"] if marker else entry["key"]


def by_key():
    out = {}
    for e in STRINGS:
        out[e["key"]] = e
    return out


def ensure_complete():
    seen = set()
    for e in STRINGS:
        for req in ["key"] + LANGUAGES:
            if req not in e or e[req] is None:
                raise AssertionError("entry missing %r: %r" % (req, e))
        if e["key"] in seen:
            raise AssertionError("duplicate key: " + e["key"])
        seen.add(e["key"])


